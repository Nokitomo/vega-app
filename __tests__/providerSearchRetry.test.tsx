import React, {act} from 'react';
import renderer from 'react-test-renderer';
import {TouchableOpacity} from 'react-native';
import {afterEach, beforeEach, describe, expect, it, jest} from '@jest/globals';
import ScrollList from '../src/screens/ScrollList';
import {providerManager} from '../src/lib/services/ProviderManager';
jest.mock('../src/lib/services/ProviderManager', () => ({providerManager: {getSearchPosts: jest.fn(), getArchiveFilters: () => ({})}}));
jest.mock('../src/lib/zustand/contentStore', () => ({__esModule: true, default: (select: any) => select({provider: {value: 'animeunity'}})}));
jest.mock('@react-navigation/native', () => ({useNavigation: () => ({navigate: jest.fn(), goBack: jest.fn()})}));
jest.mock('../src/components/ArchiveFilterModal', () => () => null);
jest.mock('../src/components/Skeleton', () => () => null);
jest.mock('../src/components/ProviderImage', () => () => null);
jest.mock('@shopify/flash-list', () => ({FlashList: (props: any) => require('react').createElement('List', props, props.ListFooterComponent)}));
jest.mock('react-i18next', () => ({useTranslation: () => ({t: (key: string) => key})}));
const search = jest.mocked(providerManager.getSearchPosts);
const props = {route: {params: {title: 'AnimeUnity', filter: 'test', providerValue: 'animeunity', isSearch: true}}} as any;
const post = {title: 'Result', link: '/result', image: '/poster'};
describe('Provider search pagination retry', () => {
  beforeEach(() => {jest.clearAllMocks(); jest.useFakeTimers(); jest.spyOn(console, 'error').mockImplementation(() => {});});
  afterEach(() => {jest.useRealTimers(); jest.restoreAllMocks();});
  it('keeps earlier cards and retries the failed page without skipping it', async () => {
    search.mockResolvedValueOnce([post]).mockRejectedValueOnce(new Error('network')).mockResolvedValueOnce([{...post, link: '/second'}]);
    let tree!: renderer.ReactTestRenderer;
    await act(async () => {tree = renderer.create(<ScrollList {...props} />);});
    await act(async () => {jest.advanceTimersByTime(350);});
    expect(tree.root.findByType('List' as any).props.data).toHaveLength(1);
    await act(async () => {tree.root.findByType('List' as any).props.onEndReached();});
    await act(async () => {jest.advanceTimersByTime(350);});
    expect(tree.root.findAllByProps({children: 'Failed to search'}).length).toBeGreaterThan(0);
    expect(tree.root.findByType('List' as any).props.data).toHaveLength(1);
    await act(async () => {tree.root.findByType('List' as any).props.onEndReached();});
    expect(search).toHaveBeenCalledTimes(2);
    const buttons = tree.root.findAllByType(TouchableOpacity);
    await act(async () => {buttons[buttons.length - 1].props.onPress();});
    await act(async () => {jest.advanceTimersByTime(350);});
    expect(search.mock.calls.map(call => call[0].page)).toEqual([1, 2, 2]);
    expect(tree.root.findByType('List' as any).props.data).toHaveLength(2);
    await act(async () => {tree.unmount();});
  });
});
